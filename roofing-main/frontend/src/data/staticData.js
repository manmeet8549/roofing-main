/**
 * Maps a remote database URL to its corresponding local public directory asset.
 * This guarantees the frontend loads from local paths even if the database is
 * awake and returns remote URLs.
 */
export function getLocalImagePath(remoteUrl) {
  if (!remoteUrl) return "";
  
  const cleanUrl = String(remoteUrl).trim();

  // 1. Check services
  const service = STATIC_SERVICES.find(s => s.image_url === cleanUrl);
  if (service) return service.local_image;

  // 2. Check projects
  const project = STATIC_PROJECTS.find(p => p.image_url === cleanUrl);
  if (project) return project.local_image;

  // 3. Check hero image
  if (STATIC_HERO_IMAGE.image_url === cleanUrl) {
    return STATIC_HERO_IMAGE.local_image;
  }

  // 4. Check materials image
  const materialsRemoteUrl = "https://customer-assets.emergentagent.com/job_5a784e05-5e78-4067-aa14-a5ab6084b2ac/artifacts/ov39vvwi_WhatsApp%20Image%202026-01-30%20at%202.39.01%20PM%20%281%29.jpeg";
  if (cleanUrl === materialsRemoteUrl) {
    return "/images/projects/project-2.jpg";
  }

  return cleanUrl; // fall back to remote URL if it's new or custom
}

